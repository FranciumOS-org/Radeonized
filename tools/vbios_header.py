#!/usr/bin/env python3
"""Generate build/plugin/gen/vbios_data.h from firmware/680m-vbios.rom, so the
VBIOS goes into the plugin without ever being committed (firmware/ and build/
are gitignored). Refuses an image that is missing, fails Linux's ATOM check
(tools/vfct.py), or does not match the SHA-256 recorded when it was extracted.

    python3 tools/vbios_header.py firmware/680m-vbios.rom build/plugin/gen/vbios_data.h
"""
import hashlib
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import vfct  # noqa: E402

# tools/efi.sh vbios, 2026-10-05 (docs/SPEC-A-START.md, B0 result)
EXPECTED_SHA256 = "27ed5802eb119409e9711bd7e3a8383c9c5725389960c6eebc154737fd8203d9"


def main():
    src, dst = sys.argv[1], sys.argv[2]
    if not os.path.exists(src):
        sys.exit(f"{src} missing: run 'sudo tools/efi.sh sysreport-on', reboot, 'sudo tools/efi.sh vbios'")
    rom = open(src, "rb").read()
    ok, why = vfct.check_atom(rom)
    if not ok:
        sys.exit(f"{src}: {why}")
    digest = hashlib.sha256(rom).hexdigest()
    if digest != EXPECTED_SHA256:
        sys.exit(f"{src}: sha256 {digest}, expected {EXPECTED_SHA256}")
    os.makedirs(os.path.dirname(dst), exist_ok=True)
    with open(dst, "w") as f:
        f.write("/* Generated by tools/vbios_header.py from %s. Do not commit. */\n" % os.path.basename(src))
        f.write("#ifndef VBIOS_DATA_H\n#define VBIOS_DATA_H\n\n#include <stdint.h>\n#include <stddef.h>\n\n")
        f.write(f"/* {len(rom)} bytes, sha256 {digest} */\nstatic const uint8_t vbios_data[] = {{\n")
        for i in range(0, len(rom), 16):
            f.write("    " + ", ".join(f"0x{b:02x}" for b in rom[i:i + 16]) + ",\n")
        f.write("};\n\nstatic const size_t vbios_data_size = sizeof(vbios_data);\n\n#endif /* VBIOS_DATA_H */\n")
    print(f"  GEN  {dst} ({len(rom)} bytes)")


if __name__ == "__main__":
    main()
