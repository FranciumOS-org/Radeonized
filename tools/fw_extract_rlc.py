#!/usr/bin/env python3
"""Extract the RLC sub-images from linux-firmware's yellow_carp_rlc.bin.

2jp. The RLC firmware file is not one image: an rlc_firmware_header_v2_2
(docs/linux-ref/amdgpu_ucode.h) describes SIX payloads in one blob - the
main ucode plus three save/restore register lists and the iram/dram images
for the LX6 core inside the RLC.

2aj substitutes only the main ucode (0x6200 at 0x100), so Apple's GC 10.3
path gets its NAVI 21 versions of the other five. Apple asks for them as
separate firmware entries - `_gc_10_3_get_fw_constants` registers
rlc_srlist_cntl / gpm_mem / srm_mem / rlc_lx6_iram / rlc_lx6_dram at
switch indices 0,1,2,0xd,0xe - and our own _IpiSetFwEntry log identifies
them by TTL id with three EXACT size matches:

    id 26 = 0x250   srlist_cntl
    id 27 = 0x600   srlist_gpm
    id 28 = 0x47a0  srlist_srm   (ours 0x4880)
    id 29 = 0x10200 rlc_iram     EXACT
    id 30 = 0x4200  rlc_dram     (ours 0x10200)

Usage: python3 tools/fw_extract_rlc.py firmware/linux/yellow_carp_rlc.bin \
           src/plugin/fw_yellow_carp_rlc.cpp
"""
import struct
import sys

HDR = 0x20          # common_firmware_header
V2_0 = HDR + 18 * 4  # 0x68
V2_1 = V2_0 + 13 * 4  # 0x9c
V2_2 = V2_1 + 4 * 4   # 0xac == 172, the whole header for v2.2


def main(src, dst):
    d = open(src, "rb").read()
    u = lambda o: struct.unpack_from("<I", d, o)[0]
    maj, minr = struct.unpack_from("<HH", d, 8)
    ipmaj, ipmin = struct.unpack_from("<HH", d, 12)
    if (maj, minr) != (2, 2):
        sys.exit(f"expected header v2.2, got v{maj}.{minr}")
    if (ipmaj, ipmin) != (10, 3):
        sys.exit(f"expected ip 10.3, got {ipmaj}.{ipmin}")

    # (C name, size field offset, offset field offset, TTL id, what)
    parts = [
        ("yc_rlc_srlist_cntl_img", V2_0 + 12, V2_0 + 16, 26, "srlist_cntl"),
        ("yc_rlc_srlist_gpm_img",  V2_0 + 28, V2_0 + 32, 27, "srlist_gpm_mem"),
        ("yc_rlc_srlist_srm_img",  V2_0 + 44, V2_0 + 48, 28, "srlist_srm_mem"),
        ("yc_rlc_iram_img",        V2_1 + 0,  V2_1 + 4,  29, "LX6 iram"),
        ("yc_rlc_dram_img",        V2_1 + 8,  V2_1 + 12, 30, "LX6 dram"),
    ]

    out = [
        "// 2jp: RLC sub-images carved out of linux-firmware's",
        "// yellow_carp_rlc.bin (header v2.2, ip 10.3 - this chip).",
        "// Generated by tools/fw_extract_rlc.py; do not edit by hand.",
        "//",
        "// Every one of these is a payload Apple's _gc_10_3_get_fw_constants",
        "// asks for as its OWN firmware entry, and which 2aj left as Apple's",
        "// Navi 21 image because it only ever swapped the main ucode.",
        "//",
        "// extern, for the same reason fw_yellow_carp.cpp says so: a const",
        "// global gets internal linkage in C++ and would be invisible to",
        "// kern_start.cpp and trip -Werror=unused-const-variable.",
        "#include <stdint.h>",
        "",
    ]
    for name, so, oo, tid, what in parts:
        size, off = u(so), u(oo)
        if size == 0 or off == 0 or off + size > len(d):
            sys.exit(f"{name}: bad size/off {size:#x}/{off:#x}")
        blob = d[off:off + size]
        out.append(f"// {what}: TTL id {tid}, size={size:#x} at file offset {off:#x}")
        out.append("__attribute__((aligned(4096)))")
        out.append(f"extern const uint8_t {name}[{size}] = {{")
        for i in range(0, size, 16):
            row = ", ".join(f"0x{b:02x}" for b in blob[i:i + 16])
            out.append(f"    {row},")
        out.append("};")
        out.append(f"extern const uint32_t {name}_size = {size:#x}u;")
        out.append("")
        print(f"  {what:16s} id={tid:3d} size={size:#8x} off={off:#8x}")

    open(dst, "w").write("\n".join(out) + "\n")
    print(f"wrote {dst}")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
