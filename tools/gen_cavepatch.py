#!/usr/bin/env python3
"""Emit the Lilu BinaryModPatch arrays that deliver the swizzle fix to EVERY
process, by patching the dyld shared cache's pages in the kernel (2nz/2oa).

Why this works where tools/cachepatch*.{py,sh} could not. 2ny established that
the cache is inside a grafted, Apple-signed cryptex and cannot be edited on
disk. Lilu does not edit it on disk. For an image in the shared cache it does
NOT use the cs_validate_page page rewrite either - that is the on-disk path,
and 2oc corrects this docstring's original claim. It uses patchSharedCache,
which runs per process at exec and writes straight into the live image:

    place = mod->startTEXT + ref->segOffs[k] + slide      (startTEXT from the .map)
    orgVmMapReadUser(...);  if bytes == patch.find
    vmProtect(RWX); orgVmMapWriteUser(..., patch.replace, place, patch.size)

The file is never touched, so the seal is irrelevant, and the patch lands in
every process - including the Apple platform binaries that strip
DYLD_INSERT_LIBRARIES. It does require a byte SOURCE on disk for Lilu to find
the patterns in: see tools/gen_stencil.py.

Two constraints shape what is emitted:

  * Lilu patches by FIND/REPLACE inside one section, not by address, so each
    patch needs a byte pattern that is unique within that section.
  * The cave cannot go in __text: the shared cache builder packs it, and this
    driver's __text contains no run of 32 identical bytes anywhere. __const is
    inside the r-x __TEXT segment, so code placed there executes, it has 27
    runs of >= 200 zero bytes, and Lilu can target it as SegmentTextConst.

  python3 tools/gen_cavepatch.py > src/plugin/rbgpu_mtlcave.h
"""
import importlib.util
import sys

spec = importlib.util.spec_from_file_location("cp", "tools/cachepatch.py")
cp = importlib.util.module_from_spec(spec)
spec.loader.exec_module(cp)

sys.path.insert(0, "tools/re")
from dyldcache import Cache                                   # noqa: E402

FN_VM      = 0x7FFB08D35A11        # amdMtl_HWL_DetermineSwizzleMode
TEXT_VM    = 0x7FFB08BF3000        # the dylib's __TEXT, as the .map reports it
CONST_VM   = 0x7FFB08FB46A0        # __const
CONST_LEN  = 906664
CAVE_VM    = 0x7FFB08FB75A0        # 16-aligned, inside a 273-byte zero run
ANCHOR     = 48                    # bytes of context before the cave
ZEROS      = 176                   # bytes of the run the cave replaces

c = Cache()
cp.CAVE_VM = CAVE_VM               # re-base the verified cave builder
cave = cp.build_cave()
assert len(cave) <= ZEROS, f"cave is {len(cave)} bytes, only {ZEROS} reserved"

const = c.read(CONST_VM, CONST_LEN)
find = c.read(CAVE_VM - ANCHOR, ANCHOR + ZEROS)
assert set(find[ANCHOR:]) == {0}, "the reserved area is not all zero"
hits = const.count(find)
assert hits == 1, f"the find pattern occurs {hits} times in __const, need 1"
repl = find[:ANCHOR] + cave + bytes(ZEROS - len(cave))

fnfind = c.read(FN_VM, 30)
assert fnfind == cp.PROLOGUE, "the function prologue moved"
text = c.read(TEXT_VM, 0x5029AE)
assert text.count(fnfind) == 1, "the prologue is not unique in __TEXT"
fnrepl = cp.detour() + fnfind[5:]


def arr(name, b):
    out = [f"static const uint8_t {name}[{len(b)}] = {{"]
    for i in range(0, len(b), 12):
        out.append("    " + " ".join(f"0x{x:02X}," for x in b[i:i + 12]))
    out.append("};")
    return "\n".join(out)


print(f"""// GENERATED by tools/gen_cavepatch.py - do not edit by hand.
//
// Delivers the RBGPU_SWIZZLE=fix policy into AMDRadeonX6000MTLDriver inside
// the dyld shared cache, via Lilu's user patcher, which rewrites pages in
// kernel memory at cs_validate_page time. Every process, no injection, and
// the cryptex is never written - 2ny proved it cannot be (Apple-signed seal),
// and this does not need to be.
//
//   function  {FN_VM:#x}  amdMtl_HWL_DetermineSwizzleMode
//   cave      {CAVE_VM:#x}  in __const, {len(cave)} bytes used of {ZEROS} reserved
//   __TEXT    {TEXT_VM:#x} (matches the cache .map)
//
// Both find patterns were checked unique in their own section against the
// live cache: the prologue once in __TEXT, the cave anchor once in __const.
#ifndef RBGPU_MTLCAVE_H
#define RBGPU_MTLCAVE_H
#include <stdint.h>

#define RBGPU_MTL_PATH "/System/Library/Extensions/AMDRadeonX6000MTLDriver.bundle/Contents/MacOS/AMDRadeonX6000MTLDriver"
#define RBGPU_MTL_CAVE_VM  {CAVE_VM:#x}ULL
#define RBGPU_MTL_TEXT_VM  {TEXT_VM:#x}ULL
#define RBGPU_MTL_FN_VM    {FN_VM:#x}ULL
#define RBGPU_MTL_CAVE_USED {len(cave)}
// The patch site is ANCHOR bytes BEFORE the cave: the cave sits in an
// all-zero run, so the pattern needs preceding context to be unique.
#define RBGPU_MTL_CAVE_ANCHOR {ANCHOR}
#define RBGPU_MTL_CAVE_RESERVED {ZEROS}

{arr("kRbMtlCaveFind", find)}

{arr("kRbMtlCaveRepl", repl)}

{arr("kRbMtlFnFind", fnfind)}

{arr("kRbMtlFnRepl", fnrepl)}

#endif""", file=sys.stderr if False else sys.stdout)
print(f"cave {len(cave)}B at {CAVE_VM:#x}; find {len(find)}B unique in __const; "
      f"prologue unique in __TEXT", file=sys.stderr)
