#!/usr/bin/env python3
"""Emit the DCN 3.0.2 -> 3.1.2 register DENY list as a C header.

2pm: Apple's DAL is dcn302 code. 2pg measured that 5332 of 5631 shared
registers (94.7 %) sit at the SAME dword offset and BASE_IDX in dcn_3_1_2, and
that the whole scanout path - OTG, HUBP, CM, DSCL, DPP, OPP, DCCG - is
identical. The 299 that MOVED are the ones DAL would write to the wrong
address on this chip.

So: pass DAL's writes through, except to those 299. The list is generated from
the two vendored headers rather than typed, because a hand-made list of 299
offsets is a rule-5 accident waiting to happen.

    python3 tools/re/dcn_denylist.py > src/common/rb_dcn_deny.h

Note the prefix change (rule 26, learned in 2pg): the 3.0.x headers spell
registers `mm<REG>` and the 3.1.x headers `reg<REG>`. A parser handling only
one silently reports near-total disagreement.
"""
import re
import sys

PAT = re.compile(r'#define\s+(?:mm|reg)(\w+?)(_BASE_IDX)?\s+(0x[0-9a-fA-F]+|\d+)\s*$')


def load(path):
    off, base = {}, {}
    with open(path, errors='ignore') as fh:
        for line in fh:
            m = PAT.match(line.rstrip('\r\n'))
            if not m:
                continue
            (base if m.group(2) else off)[m.group(1)] = int(m.group(3), 0)
    return off, base


def main():
    o302, b302 = load('docs/linux-ref/dcn_3_0_2_offset.h')
    o312, b312 = load('docs/linux-ref/dcn_3_1_2_offset.h')
    if len(o302) < 1000 or len(o312) < 1000:
        sys.exit(f"parsed too few registers ({len(o302)}, {len(o312)}) - "
                 "check the mm/reg prefix handling")

    moved = {}
    for name in set(o302) & set(o312):
        if o302[name] != o312[name] or b302.get(name) != b312.get(name):
            # The address DAL (dcn302 code) would write. That is what our hook
            # sees, so that is what the list must be keyed on.
            moved.setdefault(o302[name], []).append(name)

    print("/* GENERATED by tools/re/dcn_denylist.py - do not edit. */")
    print("/* dcn_3_0_2 dword offsets whose dcn_3_1_2 location DIFFERS.")
    print(" * Apple's DAL is dcn302 code; writing these on a DCN 3.1.2 chip")
    print(" * lands on the wrong register. 2pg/2pm. */")
    print("#ifndef RB_DCN_DENY_H")
    print("#define RB_DCN_DENY_H")
    print("#include <stdint.h>")
    print(f"#define RB_DCN_DENY_COUNT {len(moved)}u")
    print("static const uint32_t rb_dcn_deny[RB_DCN_DENY_COUNT] = {")
    for off in sorted(moved):
        names = sorted(moved[off])
        tag = names[0] + ("" if len(names) == 1 else f" (+{len(names)-1})")
        print(f"    0x{off:05x}, /* {tag} */")
    print("};")
    print("""
/* Sorted ascending, so a binary search is the lookup. */
static inline int rb_dcn_is_denied(uint32_t dword_offset)
{
    uint32_t lo = 0, hi = RB_DCN_DENY_COUNT;
    while (lo < hi) {
        uint32_t mid = lo + (hi - lo) / 2;
        if (rb_dcn_deny[mid] == dword_offset)
            return 1;
        if (rb_dcn_deny[mid] < dword_offset)
            lo = mid + 1;
        else
            hi = mid;
    }
    return 0;
}
#endif /* RB_DCN_DENY_H */""")
    print(f"/* {len(moved)} distinct offsets */", file=sys.stderr)


if __name__ == '__main__':
    main()
