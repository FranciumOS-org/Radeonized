#!/usr/bin/env python3
"""Emit the DCN 3.0.2 -> 3.1.2 register DENY list as a C header.

    python3 tools/re/dcn_denylist.py [danger|all] > src/common/rb_dcn_deny.h

2pn: Apple's DAL is dcn302 code and its register accessor takes a RAW dword
offset with BASE_IDX applied inside - established in 2pn from boot 143's four
traced reads, which resolve to unique CM0 base-2 registers as raw offsets and
to NOTHING under any absolute-index interpretation against this chip's real
DMU bases (0x12, 0xc0, 0x34c0, 0x9000, 0x2403c00 from rbdump).

So the question for each offset is NOT "did some register move" - 2pm's first
attempt asked that and was wrong, because a dword offset is not a unique
register identity: two registers with different BASE_IDX share one. The right
question is:

    for BASE_IDX 2, does a dcn302 write to offset O land on the SAME register
    in dcn312?

Three outcomes, measured:
  * same register        -> 3957 offsets, ALLOW. The whole scanout path is here.
  * nothing in dcn312    -> 1151 offsets, write is a no-op on unimplemented MMIO.
  * a DIFFERENT register -> 160 offsets, DANGEROUS. This is the deny set.

`danger` (the default) denies only the 160. `all` additionally denies the 1151,
for a boot where even a write to an unimplemented offset is unwanted - that
costs DAL ~23 % of its base-2 writes and it will very likely fail, so it is a
diagnostic setting, not a working one.

**KNOWN LIMITATION, stated rather than discovered later:** this covers BASE_IDX
2 only (5268 of this chip's 6402 DCN registers, and where 4 of 4 observed
accesses went). BASE_IDX 3 - 977 registers, overwhelmingly HDMI/DP audio
(AFMT, VPG, DIG) - has 71 dangerous offsets of its own and is NOT covered,
because which argument of `writeReg32(reg, val, uint8, uint)` carries the base
is not yet established. Audio is not needed for first light.

Note the prefix change (rule 26, learned in 2pg): 3.0.x headers spell registers
`mm<REG>`, 3.1.x spell them `reg<REG>`.
"""
import re
import sys

PAT = re.compile(r'#define\s+(?:mm|reg)(\w+?)(_BASE_IDX)?\s+(0x[0-9a-fA-F]+|\d+)\s*$')
BASE_IDX = 2


def load(path):
    off, base = {}, {}
    with open(path, errors='ignore') as fh:
        for line in fh:
            m = PAT.match(line.rstrip('\r\n'))
            if not m:
                continue
            (base if m.group(2) else off)[m.group(1)] = int(m.group(3), 0)
    return off, base


def by_offset(off, base):
    m = {}
    for name, val in off.items():
        if base.get(name) == BASE_IDX:
            m.setdefault(val, set()).add(name)
    return m


def main():
    mode = sys.argv[1] if len(sys.argv) > 1 else 'danger'
    if mode not in ('danger', 'all'):
        sys.exit("mode must be 'danger' or 'all'")

    o302, b302 = load('docs/linux-ref/dcn_3_0_2_offset.h')
    o312, b312 = load('docs/linux-ref/dcn_3_1_2_offset.h')
    if len(o302) < 1000 or len(o312) < 1000:
        sys.exit(f"parsed too few registers ({len(o302)}, {len(o312)}) - "
                 "check the mm/reg prefix handling")

    A, B = by_offset(o302, b302), by_offset(o312, b312)
    danger, nothing = {}, {}
    for offset, names302 in A.items():
        here = B.get(offset)
        if here == names302:
            continue
        (nothing if here is None else danger)[offset] = (names302, here)

    deny = dict(danger)
    if mode == 'all':
        deny.update(nothing)

    print("/* GENERATED by tools/re/dcn_denylist.py - do not edit. */")
    print(f"/* mode={mode}: BASE_IDX {BASE_IDX} dcn302 dword offsets whose dcn312")
    print(" * meaning DIFFERS. Apple's DAL is dcn302 code and its accessor takes")
    print(" * a raw dword offset, so these writes land on the wrong register. */")
    print("#ifndef RB_DCN_DENY_H")
    print("#define RB_DCN_DENY_H")
    print("#include <stdint.h>")
    print(f"#define RB_DCN_DENY_BASE_IDX {BASE_IDX}u")
    print(f"#define RB_DCN_DENY_COUNT {len(deny)}u")
    print(f"#define RB_DCN_DENY_DANGER {len(danger)}u   /* lands on a real register */")
    print(f"#define RB_DCN_DENY_VOID   {len(nothing)}u  /* nothing there in dcn312 */")
    print("static const uint32_t rb_dcn_deny[RB_DCN_DENY_COUNT] = {")
    for offset in sorted(deny):
        was, now = deny[offset]
        w = sorted(was)[0]
        n = sorted(now)[0] if now else "(unimplemented)"
        print(f"    0x{offset:05x}, /* {w} -> {n} */")
    print("};")
    print("""
/* Sorted ascending, so a binary search is the lookup. */
static inline int rb_dcn_is_denied(uint32_t dword_offset)
{
    uint32_t lo = 0, hi = RB_DCN_DENY_COUNT;
    while (lo < hi) {
        uint32_t mid = lo + (hi - lo) / 2;
        if (rb_dcn_deny[mid] == dword_offset)
            return 1;
        if (rb_dcn_deny[mid] < dword_offset)
            lo = mid + 1;
        else
            hi = mid;
    }
    return 0;
}
#endif /* RB_DCN_DENY_H */""")
    print(f"/* mode={mode}: {len(deny)} denied "
          f"({len(danger)} dangerous, {len(nothing)} void) */", file=sys.stderr)


if __name__ == '__main__':
    main()
