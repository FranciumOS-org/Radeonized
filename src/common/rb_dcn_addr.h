#ifndef RB_DCN_ADDR_H
#define RB_DCN_ADDR_H

/* 3dcn: translate a DCN 3.0.2 register address into this chip's 3.1.2 one.
 *
 * WHAT THIS IS FOR. Apple's `AMDRadeonX6000Framebuffer` drives the display
 * through a DAL built for Navi 2x. We instantiate its Navi 23 controller
 * against this device (Navi 23 is DCN 3.0.2), so every address that DAL
 * computes comes from `dcn_3_0_2_offset.h`, while the silicon is DCN 3.1.2.
 * Most registers kept their address; 298 moved. Left alone, DAL reads and
 * writes the wrong dword for those - journal 22855's "or worse, program a 3.0
 * register layout into a 3.1.2 chip", which is the stated reason this project
 * built its own framebuffer in the first place.
 *
 * The table lives in `rb_dcn_remap.h`, GENERATED by
 * `tools/re/dcn_remap_gen.py` from two pinned upstream headers. Nothing in it
 * is hand-written, and the generator refuses to emit a register that is absent
 * from the other generation rather than guessing at a rename. This file is the
 * hand-written half: the lookup, kept separate so the generated file stays
 * pure data and can be regenerated without losing logic.
 *
 * WHY A BINARY SEARCH IS SAFE HERE. The generator sorts by `from` and refuses
 * to emit duplicate `from` values at all, so the ordering a binary search
 * needs is established where the data is produced rather than assumed where it
 * is consumed. The hosttest re-checks both properties on the real table at
 * runtime, because a generator's promise is not evidence about the file that
 * is actually compiled in.
 *
 * WHAT IT DOES NOT DO. It does not know which segment an address is in, it
 * does not range-check against the aperture, and it is not a policy about
 * which registers may be written - `rb_dcn_is_denied()` remains the write
 * policy and is unaffected. This is an address translation and nothing else.
 * An address not in the table is returned unchanged, which is correct: the
 * two generations agree on it.
 */

#include <stdint.h>

#include "rb_dcn_remap.h"

/* The 3.1.2 address for a 3.0.2 one. Unmoved addresses come back unchanged.
 * `moved`, when given, receives 1 if the table had an entry and 0 if not, so a
 * caller can log or count translations without comparing the two values and
 * mistaking "not in the table" for "maps to itself" (rule 14: a path out says
 * which path it was). */
static inline uint32_t rb_dcn_addr_312(uint32_t a302, int *moved)
{
    uint32_t lo = 0, hi = (uint32_t)RB_DCN_REMAP_COUNT;

    while (lo < hi) {
        const uint32_t mid = lo + ((hi - lo) / 2u);
        const uint32_t key = rb_dcn_remap_tbl[mid].from;
        if (key == a302) {
            if (moved) { *moved = 1; }
            return rb_dcn_remap_tbl[mid].to;
        }
        if (key < a302) { lo = mid + 1u; } else { hi = mid; }
    }
    if (moved) { *moved = 0; }
    return a302;
}

/* 1 if `tbl` is sorted by `from` with no duplicates, i.e. if a binary search
 * is valid on it.
 *
 * IT TAKES THE TABLE RATHER THAN READING THE GLOBAL ONE, and that is the whole
 * point of the signature. The first draft checked `rb_dcn_remap_tbl` directly,
 * and the rule-48 sweep caught it: breaking the comparison FIRED NOTHING,
 * because the only table it could ever see is the real one, the real one is
 * sorted, and so it returned 1 either way. The check had no coverage - the
 * same "the term carries no information" defect this project has now written
 * into its own guards four times. With the table as a parameter the hosttest
 * can feed it an unsorted fixture and a duplicated one, and breaking the
 * comparison fails a test. */
static inline int rb_dcn_addr_sorted(const struct rb_dcn_remap *tbl,
                                     uint32_t count)
{
    uint32_t i;

    if (!tbl || count == 0u) { return 0; }
    for (i = 1u; i < count; i++) {
        if (tbl[i].from <= tbl[i - 1u].from) {
            return 0;
        }
    }
    return 1;
}

/* The same question asked of the table that actually got compiled in. */
static inline int rb_dcn_addr_table_ok(void)
{
    return rb_dcn_addr_sorted(rb_dcn_remap_tbl, (uint32_t)RB_DCN_REMAP_COUNT);
}

#endif /* RB_DCN_ADDR_H */
